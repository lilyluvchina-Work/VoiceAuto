import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { DEVICE_TYPES, getDefaultDeviceOptions } from '../src/config/deviceProfiles.js';
import { recordToolUsage, getToolUsageRecords, summarizeToolUsageByUser } from '../src/utils/toolUsageStore.js';
const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
const base = { startTime: 1000, endTime: 61000, user: { username: '测试用户', loginAccount: 'tester' } };
recordToolUsage({ ...base, runId: 'toy', deviceType: 'ai_toy' }, { storage });
recordToolUsage({ ...base, runId: 'speaker', deviceType: 'speaker' }, { storage });
recordToolUsage({ ...base, runId: 'legacy' }, { storage });
const records = getToolUsageRecords({ storage });
assert.equal(records.find(r => r.runId === 'toy').testProject, 'AI玩具');
assert.equal(records.find(r => r.runId === 'speaker').testProject, 'Speaker');
assert.equal(records.find(r => r.runId === 'legacy').testProject, '未记录');
assert.equal(records.find(r => r.runId === 'toy').deviceType, 'ai_toy');
assert.equal(summarizeToolUsageByUser(records)[0].totalDurationText, '3分00秒');
// Execute the actual reducer without importing the React/JSX provider in Node.
const source = readFileSync(new URL('../src/stores/testStore.jsx', import.meta.url), 'utf8');
const reducerSource = source.slice(source.indexOf('function testReducer('), source.indexOf('// Context'));
const actionTypes = new Proxy({}, { get: (_, key) => key });
const reducer = new Function('ActionTypes', 'DEVICE_TYPES', 'DEFAULT_LANGFUSE_ENV_KEY', 'getDefaultDeviceOptions', `${reducerSource}; return testReducer;`)(actionTypes, DEVICE_TYPES, 'test', getDefaultDeviceOptions);
const started = reducer({ testOptions: { device: { type: 'ai_toy' } }, playback: {}, report: {} }, { type: 'START_PLAYBACK', payload: { runId: 'first' } });
assert.equal(started.report.deviceType, 'ai_toy');
const switched = reducer(started, { type: 'SET_DEVICE_OPTIONS', payload: { type: 'speaker' } });
assert.equal(switched.testOptions.device.type, 'speaker');
assert.equal(switched.report.deviceType, 'ai_toy', 'Changing device settings must not rewrite the test snapshot');
const nextRun = reducer(switched, { type: 'START_PLAYBACK', payload: { runId: 'second' } });
assert.equal(nextRun.report.deviceType, 'speaker');
console.log('toolUsageProject tests passed');
